local corporations = require("scripts.corporations")
local preview = require("scripts.planner_preview")

script.on_event(defines.events.on_gui_opened, corporations.on_gui_opened)
script.on_event(defines.events.on_gui_click, corporations.on_gui_click)
script.on_event(defines.events.on_gui_closed, corporations.on_gui_closed)

script.on_event(defines.events.on_player_selected_area, function(event)
    preview.clear(event.player_index)
    corporations.on_player_selected_area(event)
end)
script.on_event(defines.events.on_player_alt_selected_area, function(event)
    preview.clear(event.player_index)
    corporations.on_player_alt_selected_area(event)
end)
script.on_event(defines.events.on_player_cursor_stack_changed, function(event)
    preview.on_cursor_changed(event)
    corporations.on_cursor_changed(event)
end)

script.on_event(defines.events.on_player_start_selected_area, preview.on_area)
script.on_event(defines.events.on_player_change_selected_area, preview.on_area)
script.on_event(defines.events.on_player_cancel_selected_area, function(event) preview.clear(event.player_index) end)
script.on_event(defines.events.on_player_changed_surface, preview.on_cursor_changed)
script.on_event(defines.events.on_player_changed_force, preview.on_cursor_changed)
script.on_event(defines.events.on_pre_player_died, preview.on_cursor_changed)
script.on_event(defines.events.on_player_left_game, preview.on_cursor_changed)
script.on_event(defines.events.on_player_removed, preview.on_cursor_changed)

script.on_nth_tick(120, function()
    corporations.on_district_tick()
    preview.on_tick()
end)
